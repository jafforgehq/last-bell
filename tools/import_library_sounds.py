"""Rebuilds the recorded sounds of the prison game (assets/audio/lib/) from the sound libraries kept outside the repository in ~/sfx-sources/.

The libraries are human recordings only: Kenney's Impact Sounds, RPG Audio and Interface Sounds (CC0) and single files of the Sonniss GDC Game Audio
Bundles 2017 to 2020 (royalty free, commercial use in games allowed, no attribution required, the raw files may not be redistributed). Nothing here is
generated by a model or bought. docs/assets-log.md lists the packs and their licences; the raw files are never committed, only what this tool writes.

Each GROUP below names the synthesised files the game already loads (globs under assets/audio/) and the takes cut from the recordings that stand in
for them. A take is a source file (found by a unique part of its name under ~/sfx-sources), either a fixed window (`at`, `len`) or the `pick` loudest
separate events of the file (a take of several shots is cut into single shots), with an optional gain, pitch (a speed change), filters and fades.
Every take is levelled to the files it replaces: its loudest 300 ms is brought to theirs (a loop's whole RMS to theirs), its peak is held (a soft knee, `limit`) at
their peak plus 3 dB or 14 dB over the target, whichever is higher, and never over -1 dBFS. The takes are written as mono 16-bit WAVs and assets/audio/lib/library.json maps each old file to its
takes (scripts/audio/library.gd turns them into an AudioStreamRandomizer with the small random pitch and volume, or a plain loop).

    python3 -I tools/import_library_sounds.py            # everything (about a minute)
    python3 -I tools/import_library_sounds.py zgroan     # only the groups whose name contains the word (library.json is still rewritten whole)
    python3 -I tools/import_library_sounds.py --list     # the groups and their takes

Python 3 with NumPy, and ffmpeg (/opt/homebrew/bin/ffmpeg or on the PATH) to decode and filter the sources. Run it with -I: the sources are
untrusted data, decoded by ffmpeg into raw samples, never imported.
"""
