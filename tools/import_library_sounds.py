_index = None


def find(part):
    global _index
    if _index is None:
        _index = [p for p in glob.glob(os.path.join(SRC, "**", "*"), recursive=True) if p.lower().endswith((".wav", ".ogg"))]
    hits = [p for p in _index if part in os.path.basename(p)]
    if len(hits) != 1:
        raise SystemExit("source %r matches %d files under %s" % (part, len(hits), SRC))
    return hits[0]


def decode(path, t):
    """Mono float32 at WORK_SR with the take's speed change and filters (ffmpeg reads the file; nothing else touches it)."""
    af = []
    if t["pitch"] != 1.0:
        af.append("asetrate=%d,aresample=%d" % (int(WORK_SR * t["pitch"]), WORK_SR))
    if t["hp"]:
        af.append("highpass=f=%d" % t["hp"])
    if t["lp"]:
        af.append("lowpass=f=%d" % t["lp"])
    if t["fx"]:
        af.append(t["fx"])
    cmd = [FFMPEG, "-v", "error", "-nostdin"]
    if t["at"] is not None:
        cmd += ["-ss", "%.3f" % t["at"], "-t", "%.3f" % (t["len"] / t["pitch"] + 0.5)]
    cmd += ["-i", path, "-ac", "1", "-ar", str(WORK_SR)]
    if af:
        cmd += ["-af", ",".join(af)]
    cmd += ["-f", "f32le", "-"]
    raw = subprocess.run(cmd, check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype="<f4").astype(np.float64)


def env(x, win):
    n = len(x) // win
    if n == 0:
        return np.array([float(np.sqrt(np.mean(x * x))) if len(x) else 0.0])
    return np.sqrt(np.mean(x[:n * win].reshape(n, win) ** 2, axis=1))


def events(x, n, length, gap):
    """Start samples of the `n` loudest separate events: onsets where the 5 ms envelope jumps up, at least `gap` s apart, best first."""
    win = WORK_SR // 200
    e = env(x, win)
    if len(e) < 3:
        return [0]
    db = 20 * np.log10(e + 1e-9)
    top = db.max()
    rise = np.diff(db, prepend=db[0])
    cands = [i for i in range(1, len(db)) if db[i] > top - 24 and (rise[i] > 6 or (db[i] > top - 12 and db[i - 1] < top - 18))]
    if not cands:
        cands = [int(np.argmax(db))]
    # each onset scored by its loudness just after it
    scored = sorted(((float(db[i:i + 20].max()), i) for i in cands), reverse=True)
    out = []
    for _, i in scored:
        s = max(0, i * win - win)
        if all(abs(s - o) > gap * WORK_SR for o in out) and s + int(0.05 * WORK_SR) < len(x):
            out.append(s)
        if len(out) >= n:
            break
    return out


def cut(t):
    x = decode(find(t["src"]), t)
    length = int(t["len"] * WORK_SR)
    if t["at"] is not None:
        return [x[:length]]
    return [x[s:s + length] for s in events(x, t["pick"], length, max(t["gap"], t["len"] * 0.6))]


def shape(y, fade, loop):
    y = y - np.mean(y)
    if loop:
        return y
    # trim the silence at the end, a 2 ms fade in and a fade out
    e = env(y, WORK_SR // 100)
    loud = np.where(20 * np.log10(e + 1e-9) > 20 * np.log10(e.max() + 1e-9) - 50)[0]
    if len(loud):
        y = y[:min(len(y), (loud[-1] + 2) * (WORK_SR // 100))]
    a = min(len(y), int(0.002 * WORK_SR))
    y[:a] *= np.linspace(0.0, 1.0, a)
    f = min(len(y), int(fade * WORK_SR))
    if f > 0:
        y[-f:] *= np.linspace(1.0, 0.0, f) ** 1.5
    return y


def make_loop(y, seconds):
    """A loop of `seconds`: the extra second at the end is cross-faded (equal power) into the start, so the join is not heard."""
    n = int(seconds * WORK_SR)
    x = int(min(1.0, (len(y) - n) / WORK_SR) * WORK_SR)
    if x <= 0:
        raise SystemExit("a loop source is too short")
    body = y[:n].copy()
    k = np.linspace(0.0, 1.0, x)
    body[:x] = body[:x] * np.sin(k * np.pi / 2) + y[n:n + x] * np.cos(k * np.pi / 2)
    return body


# ------------------------------------------------------------------ levels

def read_wav(path):
    with wave.open(path, "rb") as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    assert sw == 2, path
    x = np.frombuffer(raw, dtype="<i2").astype(np.float64) / 32768.0
    if ch > 1:
        x = x.reshape(-1, ch).mean(axis=1)
    return x, sr


def loud(x, sr, loop):
    """dB: a loop's whole RMS, a one-shot's loudest 300 ms."""
    if loop or len(x) <= int(0.3 * sr):
        return 20 * np.log10(np.sqrt(np.mean(x * x)) + 1e-9)
    win = int(0.3 * sr)
    c = np.cumsum(np.concatenate([[0.0], x * x]))
    best = max((c[i + win] - c[i]) / win for i in range(0, len(x) - win, max(1, win // 6)))
    return 10 * np.log10(best + 1e-12)


def peak(x):
    return 20 * np.log10(np.max(np.abs(x)) + 1e-9)


DRIVE_DB = 10.0


def limit(y, ceiling):
    """Keeps the peak at `ceiling` dBFS: a recording has a far higher crest than the synthesised sound it replaces, so at the same loudness its first
    transient would be far over it. Up to DRIVE_DB of the excess is rounded off by a soft knee (tanh: the crack of a shot gets a little denser, as a
    game's limiter would make it); what is left over that is taken off the whole take (it is then quieter than the target, and library.json says so)."""
    over = peak(y) - ceiling
    if over <= 0.0:
        return y
    if over > DRIVE_DB:
        y = y * 10 ** ((DRIVE_DB - over) / 20.0)
    c = 10 ** (ceiling / 20.0)
    k = c * 0.5
    a = np.abs(y)
    hot = a > k
    y = y.copy()
    y[hot] = np.sign(y[hot]) * (k + (c - k) * np.tanh((a[hot] - k) / (c - k)))
    return y


def target(olds, loop):
    vals, peaks = [], []
    for p in olds:
        x, sr = read_wav(p)
        vals.append(loud(x, sr, loop))
        peaks.append(peak(x))
    return float(np.mean(vals)), float(max(peaks))


def resample(y, sr):
    if sr == WORK_SR:
        return y
    n = int(round(len(y) * sr / WORK_SR))
    # (an FFT resample: band-limits as it goes, so the 22 kHz takes do not alias)
    from numpy.fft import irfft, rfft
    spec = rfft(y)
    keep = n // 2 + 1
    spec = spec[:keep] if keep <= len(spec) else np.concatenate([spec, np.zeros(keep - len(spec))])
    return irfft(spec, n) * (n / len(y))


def write_wav(path, y, sr):
    pcm = np.clip(np.round(y * 32767.0), -32768, 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm.tobytes())


def res(path):
    return "res://" + os.path.relpath(path, ROOT).replace(os.sep, "/")


# ------------------------------------------------------------------ the run

def olds_of(g):
    out = []
    for pat in g["olds"]:
        out += sorted(glob.glob(os.path.join(AUDIO, pat)))
    if not out:
        raise SystemExit("group %s: no old file matches %s" % (g["name"], g["olds"]))
    return out


def build(g, sounds, loops, notes):
    olds = olds_of(g)
    loop = g["loop"] > 0
    want, top = target(olds, loop)
    made = []
    for t in g["takes"]:
        for y in cut(t):
            if len(made) >= g["most"]:
                break
            if loop:
                y = make_loop(shape(y, 0.0, True), g["loop"])
            else:
                y = shape(y, t["fade"], False)
            y = resample(y, g["rate"])
            gain = want - loud(y, g["rate"], loop) + t["gain"]
            y = y * 10 ** (gain / 20.0)
            y = limit(y, min(-1.0, max(top + 3.0, want + 14.0)))
            name = "%s_%d.wav" % (g["name"], len(made))
            write_wav(os.path.join(OUT, name), y, g["rate"])
            made.append(name)
            notes[name] = {"from": os.path.relpath(find(t["src"]), SRC), "seconds": round(len(y) / g["rate"], 2),
                           "peak_db": round(peak(y), 2), "level_db": round(loud(y, g["rate"], loop), 2), "target_db": round(want, 2)}
    if not made:
        raise SystemExit("group %s made nothing" % g["name"])
    for o in olds:
        if loop:
            loops[res(o)] = "res://assets/audio/lib/" + made[0]
        else:
            sounds[res(o)] = ["res://assets/audio/lib/" + m for m in made]
    print("%-18s %d take(s) for %d file(s), level %.1f dB" % (g["name"], len(made), len(olds), want))


def horde(sounds, loops, notes):
    """moan_loop: the groans laid over each other (a crowd of the dead some way off), a cross-faded loop."""
    h = HORDE
    rng = np.random.default_rng(h["seed"])
    takes = []
    for name in sorted(os.listdir(OUT)):
        if name.startswith("zgroan_") and name.endswith(".wav"):
            x, sr = read_wav(os.path.join(OUT, name))
            takes.append(x if sr == WORK_SR else np.interp(np.linspace(0, len(x) - 1, int(len(x) * WORK_SR / sr)), np.arange(len(x)), x))
    n = int((h["seconds"] + 1.0) * WORK_SR)
    bed = np.zeros(n + WORK_SR * 3)
    for _ in range(h["voices"]):
        x = takes[rng.integers(len(takes))]
        k = rng.uniform(0.8, 1.05)
        y = np.interp(np.arange(0, len(x) - 1, k), np.arange(len(x)), x) * rng.uniform(0.3, 1.0)
        at = rng.integers(0, n)
        bed[at:at + len(y)] += y[:len(bed) - at]
    bed[:WORK_SR * 3] += bed[n:n + WORK_SR * 3]    # (what runs past the end comes round to the start)
    bed = bed[:n]
    y = make_loop(bed, h["seconds"])
    # a little lowpass (a crowd heard over a wall)
    y = np.convolve(y, np.ones(5) / 5.0, mode="same")
    olds = olds_of(h | {"name": "horde"})
    want, top = target(olds, True)
    y = resample(y, 22050)
    y = y * 10 ** ((want - loud(y, 22050, True)) / 20.0)
    if peak(y) > -1.0:
        y = y * 10 ** ((-1.0 - peak(y)) / 20.0)
    write_wav(os.path.join(OUT, "horde_0.wav"), y, 22050)
    notes["horde_0.wav"] = {"from": "the zgroan takes above, layered", "seconds": h["seconds"], "peak_db": round(peak(y), 2), "level_db": round(loud(y, 22050, True), 2), "target_db": round(want, 2)}
    for o in olds:
        loops[res(o)] = "res://assets/audio/lib/horde_0.wav"
    print("%-18s 1 loop from %d groans" % ("horde", len(takes)))


def main():
    if "--list" in sys.argv:
        for g in GROUPS:
            print(g["name"], g["olds"], [t["src"] for t in g["takes"]])
        return 0
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    os.makedirs(OUT, exist_ok=True)
    mapf = os.path.join(OUT, "library.json")
    old = json.load(open(mapf)) if os.path.exists(mapf) else {}
    sounds, loops, notes = dict(old.get("sounds", {})), dict(old.get("loops", {})), dict(old.get("takes", {}))
    for g in GROUPS:
        if only and not any(w in g["name"] for w in only):
            continue
        for f in glob.glob(os.path.join(OUT, g["name"] + "_[0-9]*.wav")):
            os.remove(f)
            notes.pop(os.path.basename(f), None)
        build(g, sounds, loops, notes)
    if not only or any(w in "horde" for w in only):
        horde(sounds, loops, notes)
    with open(mapf, "w") as f:
        json.dump({"about": "made by tools/import_library_sounds.py; sources and licences in docs/assets-log.md",
                   "sounds": dict(sorted(sounds.items())), "loops": dict(sorted(loops.items())), "takes": dict(sorted(notes.items()))}, f, indent=1)
    total = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT) if n.endswith(".wav"))
    print("%d takes, %d old files mapped, %d loops, %.1f MB in %s" % (len(notes), len(sounds), len(loops), total / 1048576.0, os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
